/**
 * tldraw's interface in Bulgarian.
 *
 * tldraw 3.x ships its own translations for 48 languages, and Bulgarian is not
 * one of them (`LANGUAGES` in `@tldraw/tlschema`), so a Bulgarian reader saw
 * every canvas's menu, tooltips and dialogs in English: "Menu" on the agent
 * view, the whole editor menu on a process map (#5924). tldraw takes extra
 * messages per locale through `overrides.translations`, and applies them over
 * its English for a locale it does not ship, so this is the Bulgarian it
 * lacks.
 *
 * Every key the canvases this product mounts can show is here: the main menu
 * and its submenus, the context menu, the style panel and toolbar, the
 * navigation panel, the keyboard-shortcuts dialog, the link and embed dialogs,
 * toasts and the accessibility announcements. Left out on purpose are the
 * groups that belong to tldraw.com's own app and that no canvas here renders
 * (sharing, people, files, the VS Code extension, cursor chat); a key missing
 * here falls back to tldraw's English. `tldraw-reader-language.test.ts` holds
 * the keys to tldraw's own list and every value to Bulgarian.
 *
 * Type-only import of tldraw, so this file never pulls the editor into a
 * chunk that does not already load it.
 */

"""Shared fixtures: the committed PII corpus, verified against its digest.

The corpus lives at tests/fixtures/pii/ in the repository (generated by
tests/fixtures/pii/generate.ts). ``PII_CORPUS_DIR`` overrides the location for
the image, which copies it in. A missing corpus FAILS rather than skips: a
recogniser test that silently ran on nothing would read as a pass.
"""

from __future__ import annotations

import hashlib
import json
import os
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

CORPUS_DIR = Path(os.environ.get("PII_CORPUS_DIR", ROOT.parent.parent / "tests" / "fixtures" / "pii"))


@pytest.fixture(scope="session")
def corpus() -> dict:
    raw = (CORPUS_DIR / "corpus.json").read_bytes()
    digest, name = (CORPUS_DIR / "corpus.sha256").read_text(encoding="utf-8").split()
    assert name == "corpus.json"
    assert digest == "sha256:" + hashlib.sha256(raw).hexdigest(), "corpus.json does not match corpus.sha256"
    return json.loads(raw.decode("utf-8"))


def gold(corpus: dict, entity: str, locale: str | None = None):
    """(case, text) for every ground-truth span of one type."""
    for case in corpus["cases"]:
        if locale and case["locale"] != locale:
            continue
        for span in case["spans"]:
            if span["type"] == entity:
                yield case, case["text"][span["start"] : span["end"]], span


def empty_cases(corpus: dict):
    """Cases that say there is nothing to find: refusal and missing-input."""
    return [c for c in corpus["cases"] if not c["spans"]]
